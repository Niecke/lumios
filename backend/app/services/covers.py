"""Library covers: a small JPEG built from the watermarked previews of a library.

The cover is built from ``previews/`` objects only, never from originals, so it
cannot leak an unwatermarked photo. It is generated by the ``generate_library_cover``
job on the ``photo`` queue.
"""

from __future__ import annotations

import io
import logging
import secrets

from botocore.exceptions import ClientError
from PIL import Image as PilImage, ImageOps, UnidentifiedImageError
from procrastinate.exceptions import AlreadyEnqueued
from sqlalchemy import select

from models import Image, Library, db
from services import storage
from services.redis_client import cache_delete_pattern

logger = logging.getLogger(__name__)

COVER_WIDTH = 640
COVER_HEIGHT = 400
COVER_GRID = 4
COVER_CANDIDATES = 12
COVER_DEBOUNCE_SECONDS = 30
COVER_JPEG_QUALITY = 80

_MISSING_CODES = {"NoSuchKey", "404", "NotFound"}


def enqueue_library_cover(library_id: int) -> bool:
    """Queue a (debounced) cover job for a library; never raises.

    Call it after the commit that changed the photos. Several calls within the
    debounce window give one job. Returns False when an error kept the job from
    being queued; a duplicate that is still waiting counts as queued.
    """
    # Imported here: worker.py imports the services for the job bodies.
    from worker import generate_library_cover_task, open_for_defer

    lock = f"library-cover-{library_id}"
    try:
        open_for_defer()
        generate_library_cover_task.configure(
            lock=lock,
            queueing_lock=lock,
            schedule_in={"seconds": COVER_DEBOUNCE_SECONDS},
        ).defer(library_id=library_id)
    except AlreadyEnqueued:
        pass
    except Exception:
        logger.exception("Could not queue the cover job of library %s", library_id)
        return False
    return True


def cover_url(library: Library) -> str | None:
    """Presigned URL of the library cover, or None (no cover, or presigning failed)."""
    if not library.cover_key:
        return None
    try:
        return storage.get_presigned_url(library.cover_key)
    except Exception:
        logger.warning("Could not presign the cover of library %s", library.id)
        return None


def _load_preview(image: Image, user_id: int) -> PilImage.Image | None:
    """The decoded watermarked preview, or None when it is missing or unreadable."""
    key = image.storage_path("previews", user_id=user_id)
    try:
        data = storage.get_object_bytes(key)
    except ClientError as exc:
        code = str(exc.response.get("Error", {}).get("Code", ""))
        if code in _MISSING_CODES:
            logger.info("Cover: preview of image %s is missing, skipped", image.id)
            return None
        raise
    try:
        with PilImage.open(io.BytesIO(data)) as src:
            return src.convert("RGB")
    except (UnidentifiedImageError, OSError):
        logger.info("Cover: preview of image %s cannot be decoded, skipped", image.id)
        return None


def _compose(images: list[PilImage.Image]) -> io.BytesIO:
    if len(images) >= COVER_GRID:
        cell_w, cell_h = COVER_WIDTH // 2, COVER_HEIGHT // 2
        cover = PilImage.new("RGB", (COVER_WIDTH, COVER_HEIGHT))
        positions = [(0, 0), (cell_w, 0), (0, cell_h), (cell_w, cell_h)]
        for img, pos in zip(images[:COVER_GRID], positions):
            cell = ImageOps.fit(img, (cell_w, cell_h))
            cover.paste(cell, pos)
            cell.close()
    else:
        cover = ImageOps.fit(images[0], (COVER_WIDTH, COVER_HEIGHT))
    buf = io.BytesIO()
    cover.save(buf, format="JPEG", quality=COVER_JPEG_QUALITY)
    cover.close()
    buf.seek(0)
    return buf


def _delete_old_cover(key: str | None, new_key: str | None) -> None:
    if not key or key == new_key:
        return
    try:
        storage.delete_object(key)
    except Exception:
        logger.warning("Failed to delete replaced cover from object storage key=%s", key)


def generate_library_cover(library_id: int) -> None:
    """Rebuild the cover of a library from its newest previews (app context required).

    Idempotent: every run starts from the current state. Storage errors other
    than a missing preview propagate so the job is retried.
    """
    library = db.session.get(Library, library_id)
    if library is None or library.deleted_at is not None:
        return

    candidates = (
        db.session.execute(
            select(Image)
            .where(Image.library_id == library.id, Image.deleted_at.is_(None))
            .order_by(Image.created_at.desc(), Image.id.desc())
            .limit(COVER_CANDIDATES)
        )
        .scalars()
        .all()
    )

    usable: list[PilImage.Image] = []
    try:
        for image in candidates:
            if len(usable) >= COVER_GRID:
                break
            img = _load_preview(image, library.user_id)
            if img is not None:
                usable.append(img)

        old_key = library.cover_key
        if not usable:
            if old_key:
                library.cover_key = None
                db.session.commit()
                _delete_old_cover(old_key, None)
                cache_delete_pattern(f"public:library:{library.uuid}:*")
            return

        buf = _compose(usable)
    finally:
        for img in usable:
            img.close()

    new_key = (
        f"photos/{library.user_id}/{library.id}/covers/cover-{secrets.token_hex(4)}.jpg"
    )
    storage.upload_fileobj(buf, new_key, "image/jpeg")
    library.cover_key = new_key
    db.session.commit()
    _delete_old_cover(old_key, new_key)
    cache_delete_pattern(f"public:library:{library.uuid}:*")
